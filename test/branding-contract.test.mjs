import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');

test('desktop bundle and native package are Agentic Movie Studio', async () => {
  const tauri = JSON.parse(await read('src-tauri/tauri.conf.json'));
  const cargo = await read('src-tauri/Cargo.toml');

  assert.equal(tauri.productName, 'Agentic Movie Studio');
  assert.equal(tauri.identifier, 'com.abandonedmuse.agenticmoviestudio');
  assert.equal(tauri.app.windows[0].title, 'Agentic Movie Studio');
  assert.ok(tauri.bundle.fileAssociations[0].ext.includes('ams'));
  assert.match(cargo, /^name = "agentic-movie-studio"$/m);
  assert.match(cargo, /^authors = \["Abandoned Muse"\]$/m);
  assert.doesNotMatch(cargo, /Wasserman|Sam /i);
});

test('product UI carries the new ownership and primary project format', async () => {
  const html = await read('src/index.html');
  const cork = await read('src/modules/cork-board/app.js');
  const slate = await read('src/modules/slate/assets/index-CBzKc8l5.js');

  assert.match(html, /<title>Agentic Movie Studio — Local Movie Production<\/title>/);
  assert.match(html, /<h1>AGENTIC <span class="b">MOVIE<\/span><br>STUDIO<\/h1>/);
  assert.match(html, /Built and expanded by Abandoned Muse/);
  assert.match(html, /app:'agentic-movie-studio', version:4/);
  assert.match(html, /replace\(\/\\s\+\/g,'_'\)\+'\.ams'/);
  assert.doesNotMatch(html, /Created by Sam|Support Sam|Wasserman Filmmaker Suite/i);
  assert.doesNotMatch(html, /wassermanproductions\.com|github\.com\/wassermanproductions/i);
  assert.doesNotMatch(cork, /Sam Wasserman|wassermanproductions\.com|github\.com\/wassermanproductions/i);
  assert.doesNotMatch(slate, /Sam Wasserman|wassermanproductions\.com|wasserman\.ai|ko-fi\.com\/samwasserman/i);
});

test('legacy projects remain readable without remaining the product identity', async () => {
  const html = await read('src/index.html');
  assert.match(html, /\['agentic-movie-studio','studio','scriptbreak'\]\.includes\(d\.app\)/);
  assert.match(html, /\.\(ams\|studio\|scriptbreak\|json\)/);
  assert.match(html, /Save an \.ams file first/);
});

test('README owns the product and acknowledges the original base once', async () => {
  const readme = await read('README.md');
  const notice = await read('NOTICE');
  const iconGenerator = await read('src-tauri/icons/gen_icons.py');

  assert.match(readme, /^# Agentic Movie Studio$/m);
  assert.match(readme, /rebuilt and expanded by \*\*Abandoned Muse\*\*/);
  assert.match(readme, /https:\/\/github\.com\/wassermanproductions\/scriptbreak/);
  assert.match(notice, /^Agentic Movie Studio$/m);
  assert.match(iconGenerator, /text = "AMS"/);
  assert.doesNotMatch(iconGenerator, /text = "SB"/);
});

test('MCP metadata is owned by Agentic Movie Studio', async () => {
  const pkg = JSON.parse(await read('mcp/package.json'));
  const mcp = await read('mcp/scriptbreak-mcp.mjs');

  assert.equal(pkg.name, 'agentic-movie-studio-mcp');
  assert.equal(pkg.author, 'Abandoned Muse');
  assert.equal(pkg.bin['agentic-movie-studio-mcp'], './scriptbreak-mcp.mjs');
  assert.match(mcp, /serverInfo: \{ name: 'agentic-movie-studio', version: '2\.0\.0' \}/);
  assert.match(mcp, /Generated by Agentic Movie Studio/);
  assert.doesNotMatch(mcp, /Wasserman Filmmaker Suite|Sam Wasserman/i);
});
