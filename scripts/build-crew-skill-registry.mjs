import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.join(repo, 'src', 'crew-skills');
const manifest = JSON.parse(await readFile(path.join(root, 'manifest.json'), 'utf8'));
const constitution = await readFile(path.join(root, manifest.constitution), 'utf8');
const version = String(manifest.version || '1.0.0');
const roles = {};

for (const [roleId, directory] of Object.entries(manifest.roles)) {
  const skillPath = path.join(root, directory, 'SKILL.md');
  const content = await readFile(skillPath, 'utf8');
  const name = /^name:\s*([^\n]+)$/m.exec(content)?.[1]?.trim();
  const title = /^#\s+(.+)$/m.exec(content)?.[1]?.trim();
  if (!name || !title || /\[TODO|TODO:/i.test(content)) {
    throw new Error(`Incomplete skill book for ${roleId}: ${skillPath}`);
  }
  roles[roleId] = {
    name,
    title,
    version,
    path: `crew-skills/${directory}/SKILL.md`,
    content,
  };
}

const registry = {
  schema: manifest.schema,
  version,
  constitution,
  roles,
};
const output = `/* Generated by scripts/build-crew-skill-registry.mjs. Do not hand-edit. */\n`
  + `globalThis.CREW_SKILL_REGISTRY = ${JSON.stringify(registry, null, 2)};\n`;
await writeFile(path.join(root, 'registry.js'), output, 'utf8');
console.log(`Built ${Object.keys(roles).length} crew skill books into src/crew-skills/registry.js`);
